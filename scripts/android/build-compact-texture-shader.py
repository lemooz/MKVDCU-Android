"""Build the optional BC1 -> RGB5A1 loader from pinned Xenia helpers (no network)."""
import os
from pathlib import Path
import struct
import subprocess
import tempfile
import re

root = Path(__file__).resolve().parents[2]
shaders = root / 'references/rexglue-sdk/src/graphics/shaders'
tools = Path(os.environ['LOCALAPPDATA']) / 'Android/Sdk/ndk/27.0.12077973/shader-tools/windows-x86_64'
with tempfile.TemporaryDirectory(prefix='mkvdcu-compact-shader-') as directory:
    binary = Path(directory) / 'texture.spv'
    subprocess.run([str(tools/'glslc.exe'), '--target-env=vulkan1.0', '-O', '-fshader-stage=compute',
                    str(shaders/'source/gpu/shaders/texture_load_dxt1_rgb5a1.cs.glsl'),
                    '-o', str(binary)], check=True)
    subprocess.run([str(tools/'spirv-val.exe'), '--target-env', 'vulkan1.0', str(binary)], check=True)
    assembly = subprocess.check_output([str(tools/'spirv-dis.exe'), str(binary)], text=True)
    push_type = re.search(r'%\S+ = OpTypePointer PushConstant (%\S+)', assembly).group(1)
    offsets = [int(offset) for _, offset in re.findall(
        r'OpMemberDecorate ' + re.escape(push_type) + r' (\d+) Offset (\d+)', assembly)]
    assert offsets == [0, 4, 8, 12, 16, 28, 32, 36], offsets
    words = struct.unpack('<' + 'I' * (binary.stat().st_size // 4), binary.read_bytes())
    text = ['// Generated by scripts/android/build-compact-texture-shader.py.\n',
            'const uint32_t texture_load_dxt1_rgb5a1_cs[] = {\n']
    for index in range(0, len(words), 8):
        text.append('  ' + ', '.join(f'0x{word:08x}' for word in words[index:index+8]) + ',\n')
    text.append('};\n')
    (shaders/'vulkan_spirv/texture_load_dxt1_rgb5a1_cs.h').write_text(''.join(text))
print('PASS: compact DXT1 shader compiled and spirv-val validated for Vulkan 1.0')
