"""Regenerate the small driver smoke test, then validate each SPIR-V module."""
import os, pathlib, subprocess, struct
root = pathlib.Path(__file__).resolve().parents[1]
source = root / 'MKVDCU-Recomp/references/rexglue-sdk/src/ui/android_driver'
tools = pathlib.Path(os.environ['LOCALAPPDATA']) / 'Android/Sdk/ndk/27.0.12077973/shader-tools/windows-x86_64'
output = pathlib.Path('C:/Temp/mkvdcu-driver-probe-shaders')
output.mkdir(exist_ok=True)
arrays = ['// Generated by scripts/build-driver-probe-shaders.py.\n#pragma once\n']
for stage in ('comp', 'vert', 'frag', 'tesc', 'tese'):
    spv = output / f'probe.{stage}.spv'
    subprocess.run([str(tools / 'glslc.exe'), '--target-env=vulkan1.0', str(source / f'probe.{stage}'), '-o', str(spv)], check=True)
    subprocess.run([str(tools / 'spirv-val.exe'), '--target-env', 'vulkan1.0', str(spv)], check=True)
    data = spv.read_bytes()
    words = struct.unpack('<' + 'I' * (len(data) // 4), data)
    arrays.append(f'inline constexpr uint32_t probe_{stage}[] = {{\n')
    for i in range(0, len(words), 8):
        arrays.append('  ' + ', '.join(f'0x{word:08x}' for word in words[i:i+8]) + ',\n')
    arrays.append('};\n')
(source / 'probe_shaders.h').write_text(''.join(arrays), encoding='utf-8')
